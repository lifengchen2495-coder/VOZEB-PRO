export function completeSkillValue(stage: DramaSkillStage) {
    const documents: Record<DramaSkillStage, string> = { characters: characterDocument, beats: beatsDocument, script: scriptDocument, content: contentDocument, visual: visualDocument, "video-prompts": visualDocument };
    return {
        document: documents[stage],
        assumptions: ["未交代的制作细节按动画方案补足，待人工审阅。"],
        changes: ["把查证情节集中在旧书店内，增加录音备份作为小反转。"],
        checks: DRAMA_SKILL_CHECKLISTS[stage].map((check) => ({ ...check, passed: true, detail: `模型自查：已在正文对应部分说明${check.title}，仍需人工审阅。` })),
    };
}

/** 测试用手工小样，不加入生产提示词或动态填充正文。 */
export function fixtureDramaSkillReport(stage: DramaSkillStage): DramaSkillReport {
    const definition = manifest.skills.find((skill) => skill.stages.includes(stage));
    if (!definition) throw new Error(`未知 fixture 阶段：${stage}`);
    return { skillId: definition.id, version: definition.version, ...completeSkillValue(stage) };
}

